DECLARE
 v_count NUMBER;
BEGIN
 SELECT COUNT(*) INTO v_count FROM atrace.anon_inclusions;
 IF v_count > 0 THEN
 DBMS_OUTPUT.PUT_LINE(' Loaded ' || v_count || ' custom inclusion(s)');
 ELSE
 DBMS_OUTPUT.PUT_LINE(' No custom inclusions loaded (file empty or all commented)');
 END IF;
END;
