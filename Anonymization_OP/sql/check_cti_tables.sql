SET PAGESIZE 200
SET LINESIZE 150
SET HEADING ON
SET FEEDBACK OFF
COLUMN table_name FORMAT A35
COLUMN owner FORMAT A10

PROMPT
PROMPT ====================================================================
PROMPT CTI TABLE EXISTENCE CHECK
PROMPT ====================================================================
PROMPT

-- Check all CTI tables from the reference list
SELECT 
 t.table_name AS "Table Name",
 CASE WHEN a.table_name IS NOT NULL THEN 'YES' ELSE 'NO' END AS "Exists?",
 a.owner AS "Owner",
 a.num_rows AS "Row Count"
FROM (
 -- CM tables (Cash Management)
 SELECT 'CM_ACCOUNT_OF_BKSTMT_FILE' AS table_name FROM dual UNION ALL
 SELECT 'CM_ARCHIVED_FORECAST' FROM dual UNION ALL
 SELECT 'CM_BKSTMT_FILE_CONFIG' FROM dual UNION ALL
 SELECT 'CM_BSI_BANK_STATEMENT' FROM dual UNION ALL
 SELECT 'CM_CASH_CONCENT_ACCOUNTS' FROM dual UNION ALL
 SELECT 'CM_CASH_CONCENT_HEADER' FROM dual UNION ALL
 SELECT 'CM_DEAL_DEAL' FROM dual UNION ALL
 SELECT 'CM_FLI_FLOW' FROM dual UNION ALL
 SELECT 'CM_FLOW_TO_PAY_RULES' FROM dual UNION ALL
 SELECT 'CM_FOI_FORECAST' FROM dual UNION ALL
 SELECT 'CM_FORECAST' FROM dual UNION ALL
 SELECT 'CM_PAYT_PAYMENT' FROM dual UNION ALL
 SELECT 'CM_POOLING_CONVENTION' FROM dual UNION ALL
 SELECT 'CM_POOLING_METHOD' FROM dual UNION ALL
 SELECT 'CM_PROCESS' FROM dual UNION ALL
 SELECT 'CMS_FILE_BKD' FROM dual UNION ALL
 SELECT 'CM_CMS_EXCEPTIONS' FROM dual UNION ALL
 -- DM tables (Deal Management)
 SELECT 'DM_HEDGE_REQUEST' FROM dual UNION ALL
 SELECT 'DM_HR_AUTOVALID_BKD' FROM dual UNION ALL
 SELECT 'DM_HR_CTRP_MAP' FROM dual UNION ALL
 SELECT 'DM_HR_CUTOFF_BKD' FROM dual UNION ALL
 SELECT 'DM_HR_LIMIT_BKD' FROM dual UNION ALL
 SELECT 'DM_HR_PTF_BKD' FROM dual UNION ALL
 SELECT 'DM_HR_QUOTATION' FROM dual UNION ALL
 -- TP tables (Third Party)
 SELECT 'TP_BUSINESS_PROFILE' FROM dual UNION ALL
 SELECT 'TP_COMM_ENTITY_DIM' FROM dual UNION ALL
 SELECT 'TP_CONTACT' FROM dual UNION ALL
 SELECT 'TP_DATA_PROFILE_BANKACCOUNT' FROM dual UNION ALL
 SELECT 'TP_DATA_PROFILE_CTRP' FROM dual UNION ALL
 SELECT 'TP_DATA_PROFILE_ENTITY' FROM dual UNION ALL
 SELECT 'TP_DATA_PROFILE_PTF' FROM dual UNION ALL
 SELECT 'TP_POS_SNAPSHOT' FROM dual UNION ALL
 SELECT 'TP_POS_SNAPSHOT_RESULTS' FROM dual UNION ALL
 SELECT 'TP_TENANT_ENTITY' FROM dual UNION ALL
 SELECT 'TP_USERS' FROM dual UNION ALL
 SELECT 'TP_WV_MAILING_RULE' FROM dual UNION ALL
 SELECT 'TP_WV_TRANSITION_RULE' FROM dual UNION ALL
 -- UAA tables
 SELECT 'UAA_USERS' FROM dual
) t
LEFT JOIN all_tables a ON UPPER(a.table_name) = t.table_name
ORDER BY t.table_name;

