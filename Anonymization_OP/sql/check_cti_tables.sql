-- Check if specific columns exist in key tables
SELECT 
 expected.tbl AS table_name,
 expected.col AS column_name,
 CASE WHEN c.column_name IS NOT NULL THEN 'EXISTS' ELSE 'MISSING' END AS status
FROM (
 -- CM tables key columns
 SELECT 'CM_ACCOUNT_OF_BKSTMT_FILE' AS tbl, 'ENTITY' AS col FROM dual UNION ALL
 SELECT 'CM_ACCOUNT_OF_BKSTMT_FILE', 'ACCOUNT' FROM dual UNION ALL
 SELECT 'CM_ACCOUNT_OF_BKSTMT_FILE', 'BANK' FROM dual UNION ALL
 SELECT 'CM_CASH_CONCENT_HEADER', 'ENTITY' FROM dual UNION ALL
 SELECT 'CM_CASH_CONCENT_HEADER', 'CONTREPARTIE' FROM dual UNION ALL
 SELECT 'CM_CASH_CONCENT_HEADER', 'MASTER_ACCOUNT' FROM dual UNION ALL
 SELECT 'CM_DEAL_DEAL', 'ENTITY' FROM dual UNION ALL
 SELECT 'CM_DEAL_DEAL', 'CONTREPARTIE' FROM dual UNION ALL
 SELECT 'CM_DEAL_DEAL', 'COMPTE_TIERS' FROM dual UNION ALL
 SELECT 'CM_DEAL_DEAL', 'CLEARING_MEMBER' FROM dual UNION ALL
 SELECT 'CM_FLI_FLOW', 'ENTITY' FROM dual UNION ALL
 SELECT 'CM_FLI_FLOW', 'COUNTERPARTY' FROM dual UNION ALL
 SELECT 'CM_FORECAST', 'ENTITY' FROM dual UNION ALL
 SELECT 'CM_FORECAST', 'BANK' FROM dual UNION ALL
 SELECT 'CM_PAYT_PAYMENT', 'PORTFOLIO' FROM dual UNION ALL
 SELECT 'CM_PAYT_PAYMENT', 'CPTY_ACCOUNT_CODE' FROM dual UNION ALL
 -- DM tables key columns
 SELECT 'DM_HEDGE_REQUEST', 'ENTITY' FROM dual UNION ALL
 SELECT 'DM_HEDGE_REQUEST', 'COUNTERPARTY' FROM dual UNION ALL
 SELECT 'DM_HR_QUOTATION', 'ENTITY' FROM dual UNION ALL
 SELECT 'DM_HR_QUOTATION', 'ACCOUNT' FROM dual UNION ALL
 -- TP tables key columns
 SELECT 'TP_COMM_ENTITY_DIM', 'ENTITY' FROM dual UNION ALL
 SELECT 'TP_COMM_ENTITY_DIM', 'PHONE' FROM dual UNION ALL
 SELECT 'TP_CONTACT', 'ENTITY' FROM dual UNION ALL
 SELECT 'TP_POS_SNAPSHOT_RESULTS', 'EMAIL' FROM dual UNION ALL
 SELECT 'TP_WV_MAILING_RULE', 'ENTITY' FROM dual UNION ALL
 SELECT 'TP_WV_MAILING_RULE', 'FIRSTNAME' FROM dual UNION ALL
 -- UAA tables
 SELECT 'UAA_USERS', 'EMAIL' FROM dual UNION ALL
 SELECT 'UAA_USERS', 'FIRSTNAME' FROM dual
) expected
LEFT JOIN all_tab_columns c 
 ON UPPER(c.table_name) = expected.tbl 
 AND UPPER(c.column_name) = expected.col
ORDER BY expected.tbl, expected.col;

